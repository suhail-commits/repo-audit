import type { Finding } from "@vibe/shared";

import { arr, countOf, duration, list, num, str } from "./format";

type Data = Finding["data"];

export interface PersonaTemplate {
  body(data: Data, finding: Finding): string;
  /** Consequence, fix, or cost — whichever this persona needs. */
  detail?(data: Data, finding: Finding): string[];
}

export interface RuleTemplate {
  title(data: Data, finding: Finding): string;
  founder: PersonaTemplate;
  engineer: PersonaTemplate;
  acquirer: PersonaTemplate;
}

