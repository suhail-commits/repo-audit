/**
 * Used for any rule without a hand-written template.
 *
 * This is load-bearing rather than a safety net: once vendored scanners are wired
 * in, they will emit far more rule IDs than we will ever template by hand, and
 * every one of them still has to read as a sentence.
 */
export const FALLBACK_TEMPLATE: RuleTemplate = {
  title: (_d, f) => f.title,
  founder: {
    body: (_d, f) =>
      `${f.title}. This was flagged as a ${f.severity} issue in your code.`,
    detail: (_d, f) =>
      f.locations.length > 0
        ? [`Found in ${list(f.locations.map((l) => l.file))}.`]
        : [],
  },
  engineer: {
    body: (_d, f) => f.title,
    detail: (_d, f) =>
      f.locations
        .slice(0, 5)
        .map((l) => `${l.file}${l.line ? `:${l.line}` : ""}`),
  },
  acquirer: {
    body: (_d, f) => `${f.title} (severity: ${f.severity}).`,
    detail: (_d, f) =>
      f.estimatedFixMinutes
        ? [`Remediation: ${duration(f.estimatedFixMinutes)}.`]
        : [],
  },
};

/** Signal-level evidence lines are already human-readable; this only tidies them. */
export function evidenceLine(text: string): string {
  return text.endsWith(".") ? text : `${text}.`;
}

export function templateFor(ruleId: string): RuleTemplate {
  return RULE_TEMPLATES[ruleId] ?? FALLBACK_TEMPLATE;
}

/** Exposed so tests can assert every emitted rule has a real template. */
export function templatedRuleIds(): string[] {
  return Object.keys(RULE_TEMPLATES).sort();
}

