import type { Finding, Signal } from "@vibe/shared";

import type { AnalysisContext } from "../context";

/**
 * Artifacts left behind by AI tooling, in two families.
 *
 * **Builders** (`kind: "builder"`) are no-code generators — Lovable, Bolt, v0.
 * Their markers say the project was *scaffolded* by a generator, though it may
 * have been developed by hand for months since.
 *
 * **Agents** (`kind: "agent"`) are coding assistants driven from an editor or
 * CLI. Their marker is usually a config file the developer wrote *for* the
 * agent — `CLAUDE.md`, `.cursorrules`, `.github/copilot-instructions.md`. That
 * is arguably the stronger evidence of the two: nobody maintains instructions
 * for a tool they do not use, whereas an export marker can be years stale.
 *
 * Both are close to ground truth, so both emit findings marked `certain` — the
 * file either exists or it does not. They do *not* make the dimension score
 * certain; that is coverage, and finding a config file says nothing about how
 * much of the evidence we managed to gather.
 *
 * They stay separate because they support different claims: the report should
 * not conflate "scaffolded by Lovable" with "developed with Claude Code".
 *
 * One matcher serves both — splitting it would duplicate roughly forty lines,
 * which our own `duplicate-logic` signal would rightly flag.
 */

export const BUILDER_WEIGHT = 2.5;
/**
 * Weighted above the builder markers, and level with commit attribution.
 *
 * A committed agent config is maintained alongside the code, so it implies
 * *ongoing* use. A builder artifact records a one-time export that may be years
 * stale. It is not weighted higher than `agent-trailers`, because a per-commit
 * trailer is direct evidence of who wrote a change, where a config file is
 * evidence of how the project is set up.
 */
export const AGENT_WEIGHT = 3;

type MarkerKind = "builder" | "agent";

interface ToolMarker {
  tool: string;
  kind: MarkerKind;
  /** Exact repo-relative paths whose presence identifies the tool. */
  paths?: string[];
  /** Path prefixes/segments. */
  pathPatterns?: RegExp[];
  /** Dependency names that only this tool adds. */
  dependencies?: string[];
  /** Text in README or package.json name. */
  text?: RegExp;
}

