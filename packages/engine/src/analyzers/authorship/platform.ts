export interface ToolHit {
  tool: string;
  kind: MarkerKind;
  evidence: string;
}

export function detectTooling(ctx: AnalysisContext): ToolHit[] {
  const hits: ToolHit[] = [];
  const allPaths = ctx.files.all().map((f) => f.relPath);

  // Only README and package manifests are searched for marketing text, so a
  // passing mention of "v0.dev" inside source code does not trigger a match.
  const textSources = ctx.files
    .all()
    .filter(
      (f) =>
        /^readme(\.[a-z]+)?$/i.test(f.relPath) ||
        f.relPath.endsWith("package.json"),
    );

  for (const marker of MARKERS) {
    const add = (evidence: string) =>
      hits.push({ tool: marker.tool, kind: marker.kind, evidence });

    for (const path of marker.paths ?? []) {
      if (ctx.files.has(path)) add(`\`${path}\` present`);
    }
    for (const pattern of marker.pathPatterns ?? []) {
      const match = allPaths.find((p) => pattern.test(p));
      if (match) add(`\`${match}\` present`);
    }
    for (const dep of marker.dependencies ?? []) {
      if (ctx.frameworks.dependencies[dep]) add(`depends on \`${dep}\``);
    }
    if (marker.text) {
      const hit = textSources.find((f) => marker.text!.test(f.content));
      if (hit) add(`referenced in \`${hit.relPath}\``);
    }
  }

  // One entry per tool, keeping the first (most specific) piece of evidence.
  const seen = new Set<string>();
  return hits.filter((h) => {
    if (seen.has(h.tool)) return false;
    seen.add(h.tool);
    return true;
  });
}

/** Back-compat alias: builders only. */
export function detectPlatforms(ctx: AnalysisContext): ToolHit[] {
  return detectTooling(ctx).filter((h) => h.kind === "builder");
}

export function platformSignal(ctx: AnalysisContext): Signal {
  const hits = detectPlatforms(ctx);

  return {
    id: "builder-platform",
    value: hits.length > 0 ? 1 : 0,
    weight: BUILDER_WEIGHT,
    available: true,
    evidence: hits.map((h) => `${h.tool}: ${h.evidence}`),
  };
}

/**
 * Coding-agent configuration committed to the repository.
 *
 * Ground truth for "an AI agent was set up to work on this codebase" — a
 * narrower claim than "this code was generated", and the finding wording keeps
 * that distinction. The score treats it as strong evidence because in practice
 * nobody writes and maintains agent instructions for an agent they never run.
 */
export function agentToolingSignal(ctx: AnalysisContext): Signal {
  const hits = detectTooling(ctx).filter((h) => h.kind === "agent");

  return {
    id: "agent-tooling",
    value: hits.length > 0 ? 1 : 0,
    weight: AGENT_WEIGHT,
    available: true,
    evidence: hits.map((h) => `${h.tool}: ${h.evidence}`),
  };
}

export function platformFindings(ctx: AnalysisContext): Finding[] {
  const all = detectTooling(ctx);
  const findings: Finding[] = [];

  const builders = all.filter((h) => h.kind === "builder");
  if (builders.length > 0) {
    findings.push({
      ruleId: "ai-builder-platform",
      dimension: "authorship",
      severity: "info",
      confidence: "certain",
      source: "builtin",
      title: `Scaffolded by ${builders.map((h) => h.tool).join(", ")}`,
      locations: [],
      data: {
        platforms: builders.map((h) => h.tool),
        evidence: builders.map((h) => h.evidence),
      },
    });
  }

  const agents = all.filter((h) => h.kind === "agent");
  if (agents.length > 0) {
    findings.push({
      ruleId: "ai-agent-tooling",
      dimension: "authorship",
      severity: "info",
      confidence: "certain",
      source: "builtin",
      title: `Configured for AI-assisted development with ${agents
        .map((h) => h.tool)
        .join(", ")}`,
      locations: [],
      data: {
        tools: agents.map((h) => h.tool),
        evidence: agents.map((h) => h.evidence),
      },
    });
  }

  return findings;
}
